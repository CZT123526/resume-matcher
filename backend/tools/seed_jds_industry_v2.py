def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    base = BASE
    for a in sys.argv[1:]:
        if a.startswith("--base="):
            base = a.split("=", 1)[1]
    created, skipped, failed = 0, 0, []
    for jd in JDS:
        content = "\n".join(
            [f"{jd['meta'][0]}", f"{jd['meta'][1]}", "", "岗位职责："]
            + [f"{i+1}、{d}" for i, d in enumerate(jd["duties"])]
            + ["", "任职要求：",
               f"1、专业：{jd['reqs']['专业']}",
               f"2、学历：{jd['reqs']['学历']}",
               "3、素质要求："]
            + [f"（{i+1}）{q}" for i, q in enumerate(jd["reqs"]["素质"])]
            + ["", "公司信息：行业内成长型企业，业务稳定扩张，团队氛围务实，晋升通道清晰，五险一金齐全，欢迎踏实肯干的年轻人加入。"]
        )
        try:
            exist = httpx.get(f"{base}/api/jds?keyword={jd['title']}&page=1&page_size=50", timeout=15).json()["data"]
            if any(it["title"] == jd["title"] for it in exist.get("items", [])):
                skipped += 1
                continue
            r = httpx.post(f"{base}/api/jds", json={"title": jd["title"], "content": content}, timeout=30)
            if r.status_code in (200, 201):
                created += 1
            else:
                failed.append(f"{jd['title']}: HTTP {r.status_code} {r.text[:100]}")
        except Exception as exc:
            failed.append(f"{jd['title']}: {exc}")
    print(f"[JD种子v2] 新建 {created} / 已存在跳过 {skipped} / 失败 {len(failed)}")
    for f in failed:
        print("  ✗", f)
    return 0 if not failed else 1


if __name__ == "__main__":
    sys.exit(main())
