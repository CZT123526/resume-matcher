def build_content(jd: dict) -> str:
    """拼 Boss 直聘详情页格式的 JD 全文（全角括号序号与截图一致）"""
    reqs = jd["reqs"]
    lines = [*jd["meta"], "", "岗位职责："]
    lines += [f"{i}.{d}" for i, d in enumerate(jd["duties"], 1)]
    lines += ["", "任职要求：", f"1.专业要求：{reqs['专业']}", f"2.学历要求：{reqs['学历']}", "3.素质要求："]
    lines += [f"（{i}）{q}" for i, q in enumerate(reqs["素质"], 1)]
    lines += ["", jd["company"], jd["scale"]]
    return "\n".join(lines)


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    existing = {}
    with httpx.Client(timeout=30) as c:
        page = 1
        while True:
            d = c.get(f"{BASE}/api/jds?page={page}&page_size=100").json()["data"]
            for it in d["items"]:
                existing[it["title"]] = it["jd_id"]
            if len(existing) >= d["total"]:
                break
            page += 1

        created, skipped = [], []
        for jd in JDS:
            if jd["title"] in existing:
                skipped.append(jd["title"])
                continue
            content = build_content(jd)
            r = c.post(f"{BASE}/api/jds", json={"title": jd["title"], "content": content})
            if r.status_code == 200 and r.json()["code"] == 0:
                created.append(jd["title"])
            else:
                print(f"  ✗ {jd['title']}: HTTP {r.status_code} {r.text[:120]}")
    print(f"新建 {len(created)} 条 / 跳过已存在 {len(skipped)} 条")
    for t in created:
        print(f"  + {t}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
